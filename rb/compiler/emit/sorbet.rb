# typed: false
# frozen_string_literal: true

module Swill
  module Ruby2JS
    # Generated Sorbet artifacts: RBIs for declared accessors and typed probes
    # for declaration expressions. Neither is executed or shipped.
    class Compiler
        def rbi
          lines = ["# typed: true", "# Generated by the spike compiler. Do not edit."]
          knowledge.local.each do |entry|
            mixin = entry["kind"] == "mixin"
            properties = mixin ? entry["included_properties"] : entry["properties"]
            hidden = entry["methods"].select { |method| method["visibility"] }
            unless mixin && properties.empty? && hidden.empty?
              declaration = "#{mixin ? 'module' : 'class'} #{entry['name']}"
              if !mixin && entry["parent"]
                declaration << " < #{knowledge.resolve(entry['parent'], entry['scope'])}"
              end
              lines << declaration
              lines << "  extend T::Sig"
              properties.each do |property|
                name, type = property.values_at("name", "type")
                lines << "  sig { returns(#{type}) }"
                lines << "  def #{name}; end"
                if !property["computed"] || property["writer"]
                  lines << "  sig { params(value: #{type}).returns(#{type}) }"
                  lines << "  def #{name}=(value); end"
                end
              end
              # A macro's forwarded methods are real, typed members.
              entry["methods"].select { |method| method["to"] && !method["visibility"] }.each do |method|
                lines.concat(forward_rbi(method))
              end
              # Methods the body made private or protected are declared
              # again under that visibility, so Sorbet checks their callers.
              %w[protected private].each do |visibility|
                members = hidden.select { |method| method["visibility"] == visibility }
                next if members.empty?
                lines << "  #{visibility}"
                members.each do |method|
                  if method["to"]
                    lines.concat(forward_rbi(method))
                  else
                    lines << "  def #{method['name']}#{formals_rbi(method['formals'])}; end"
                  end
                end
              end
              lines << "end"
            end
            if mixin && entry["extends_class_methods"]
              lines << "module #{entry['name']}::ClassMethods"
              lines << "  extend T::Sig"
              entry["registries"].each do |registry|
                collection = registry["initial"] == "array" ? "T::Array[T.untyped]" : "T::Hash[T.untyped, T.untyped]"
                lines << "  sig { returns(#{collection}) }"
                lines << "  def #{registry['name']}; end"
              end
              entry["settings"].each do |name|
                lines << "  sig { params(values: T.untyped).returns(T.untyped) }"
                lines << "  def #{name}(*values); end"
              end
              lines << "end"
            end
          end
          lines.join("\n") + "\n"
        end

        def forward_rbi(method)
          parameters = method["parameters"].map { |name, type| "#{name}: #{type}" }.join(", ")
          signature = parameters.empty? ? "" : "params(#{parameters})."
          arguments = method["parameters"].keys.join(", ")
          definition = arguments.empty? ? method["name"] : "#{method['name']}(#{arguments})"
          ["  sig { #{signature}returns(#{method['returns']}) }", "  def #{definition}; end"]
        end

        # A method's parameter list as an untyped RBI declaration, matching
        # the definition's arity so Sorbet does not report a redefinition.
        def formals_rbi(formals)
          return "" if formals.nil? || formals.empty?
          list = formals.map do |formal|
            name = formal["name"]
            case formal["kind"]
            when "req" then name
            when "opt" then "#{name} = T.unsafe(nil)"
            when "rest" then "*#{name}"
            when "keyreq" then "#{name}:"
            when "key" then "#{name}: T.unsafe(nil)"
            when "keyrest" then "**#{name}"
            when "block" then "&#{name}"
            end
          end
          "(#{list.join(', ')})"
        end

        # Sorbet can bind DSL blocks to the instance, but a single property macro
        # signature cannot express the different return type of every declaration.
        # Check each expression as a typed instance method as well. These methods
        # are never loaded on MRI or emitted into JavaScript.
        def type_probes
          lines = ["# typed: true", "# Generated declaration expression checks; never executed."]
          knowledge.local.select { |entry| entry["kind"] == "class" }.each do |entry|
            lines << "class #{entry['name']}"
            lines << "  extend T::Sig"
            entry["properties"].each do |property|
              lines << "  sig { returns(#{property['type']}) }"
              lines << "  def __spike_check_#{property['js']}"
              # A stored default is a literal value; a computed property is
              # the block's source, checked in the receiver's own scope.
              lines << (property["computed"] ? property["expression"] : property["default"].inspect)
              lines << "  end"
            end
            lines << "end"
          end
          lines.join("\n") + "\n"
        end

    end
  end
end
