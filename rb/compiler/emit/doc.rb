# typed: false
# frozen_string_literal: true

module Swill
  module Ruby2JS
    # The declaration reference, generated from the same knowledge the RBI and
    # the metadata come from. Hand-maintaining this table would drift the first
    # time a macro was added; reading it from the compiler cannot.
    class Compiler
      # Markdown describing every declaration each class makes: its properties
      # and how each was declared, the macros it defines for its subclasses,
      # and its registries and settings.
      def declaration_reference
        lines = [
          "# Declaration reference",
          "",
          "Generated by `rake rdoc` from the compiler's knowledge of the framework.",
          "Every property below is installed by a declaration in a class body; see",
          "[Bindings](bindings.md) for how they are observed and [Models](models.md)",
          "for the model layer's own macros."
        ]

        documented = knowledge.local.reject { |entry| entry["kind"] == "mixin" && declarations_of(entry).empty? }
        documented.sort_by { |entry| entry["name"] }.each do |entry|
          section = declaration_section(entry)
          next if section.empty?
          lines << ""
          lines << "## #{entry['name']}"
          lines.concat(section)
        end

        lines.join("\n") + "\n"
      end

      private

      def declarations_of(entry)
        (entry["properties"] || []) + (entry["included_properties"] || [])
      end

      def declaration_section(entry)
        lines = []
        properties = declarations_of(entry)

        unless properties.empty?
          lines << ""
          lines << "| Property | Declared as | Type | Notes |"
          lines << "| --- | --- | --- | --- |"
          properties.sort_by { |property| property["name"] }.each do |property|
            kind, notes = describe_declaration(property)
            lines << "| `#{property['name']}` | #{kind} | `#{property['type']}` | #{notes} |"
          end
        end

        macros = entry["macros"] || []
        unless macros.empty?
          lines << ""
          lines << "Declares #{macros.sort.map { |name| "`#{name}`" }.join(', ')} for its subclasses."
        end

        registries = entry["registries"] || []
        unless registries.empty?
          lines << ""
          lines << "Registries: #{registries.map { |r| "`#{r['name']}`" }.join(', ')}."
        end

        settings = entry["settings"] || []
        unless settings.empty?
          lines << ""
          lines << "Settings: #{settings.map { |name| "`#{name}`" }.join(', ')}."
        end

        restorations = entry["restorations"] || []
        unless restorations.empty?
          lines << ""
          lines << "Restorable paths: #{restorations.map { |r| "`#{r['path']}`" }.join(', ')}."
        end

        lines
      end

      # A property records how it was declared, so the reference can name the
      # macro a reader would have written rather than the protocol underneath.
      def describe_declaration(property)
        if property["outlet"]
          ["outlet", property["optional"] ? "Optional; nil when no element matches." : "Connected at awakening."]
        elsif property["attribute"]
          ["attribute", "Wire key `#{property['key']}`.#{default_note(property)}"]
        elsif property["computed"]
          ["computed", "Read-only; recomputed when what it reads changes."]
        else
          ["property", default_note(property).strip]
        end
      end

      def default_note(property)
        return "" unless property.key?("default")
        " Default `#{property['default'].inspect}`."
      end
    end
  end
end
